"""Generates the compressed power-of-five table embedded in include/yk/json20.hpp
and the full reference table used by tests/number.cpp.

F(q) is 5^q scaled into [2^127, 2^128) and rounded down, for q in [Q_MIN, Q_MAX].
Every table the number conversions need derives from it:
  Eisel-Lemire (fast_float's power_of_five_128, q in [-342, 308]):
      F(q) + (1 if -27 <= q < 0 else 0)
  Dragonbox binary64 cache (k in [-292, 326]):
      F(k) + (0 if F(k) is exact, i.e. 0 <= k <= 55, else 1)
  Dragonbox binary32 cache (k in [-31, 46], 64 bits):
      high 64 bits of F(k), plus 1 unless F(k) is exact with zero low bits
(each checked entry by entry against the published tables of fast_float and
Dragonbox; see docs/design-notes.md).

The embedded form stores every 27th F (on multiples of 27, so q = 0, 27, 54
are exact bases) and recovers the rest as the top 128 bits of
base * 5^offset plus a 2-bit correction. This script verifies that the
recovery reproduces every F(q) exactly.

usage: python3 tools/gen_pow5_table.py   (prints the C++ constants and writes
tests/pow5_reference.inc)
"""

import os

Q_MIN, Q_MAX = -342, 326
RATIO = 27
GRID0 = -351


def pow5_floor(q):
    """(F(q), whether the scaling is exact)"""
    if q >= 0:
        p = 5 ** q
        s = p.bit_length() - 128
        if s >= 0:
            return p >> s, (p & ((1 << s) - 1)) == 0
        return p << -s, True
    p = 5 ** -q
    b = 127 + p.bit_length()
    while (1 << b) // p >= 1 << 128:
        b -= 1
    while (1 << b) // p < 1 << 127:
        b += 1
    return (1 << b) // p, (1 << b) % p == 0


def recover(base, off):
    prod = base * 5 ** off
    return prod >> (prod.bit_length() - 128)


def main():
    bases = [pow5_floor(qb)[0] for qb in range(GRID0, Q_MAX + 1, RATIO)]
    corrections = []
    for q in range(Q_MIN, Q_MAX + 1):
        i, off = divmod(q - GRID0, RATIO)
        delta = pow5_floor(q)[0] - recover(bases[i], off)
        assert 0 <= delta <= 3, (q, delta)
        corrections.append(delta)

    words = []
    for start in range(0, len(corrections), 32):
        w = 0
        for j, d in enumerate(corrections[start:start + 32]):
            w |= d << (2 * j)
        words.append(w)

    print('  static constexpr u128 bases[] = {')
    for b in bases:
        print(f'      {{0x{b >> 64:016x}, 0x{b & (2**64 - 1):016x}}},')
    print('  };')
    print('  static constexpr std::uint64_t corrections[] = {')
    for w in words:
        print(f'      0x{w:016x},')
    print('  };')

    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, '..', 'tests', 'pow5_reference.inc'), 'w') as out:
        out.write(f'// generated by tools/gen_pow5_table.py: F(q) for q = {Q_MIN} ... {Q_MAX}\n')
        for q in range(Q_MIN, Q_MAX + 1):
            v = pow5_floor(q)[0]
            out.write(f'{{0x{v >> 64:016x}, 0x{v & (2**64 - 1):016x}}},\n')


if __name__ == '__main__':
    main()
