"""Generates json20 as a single header from the headers under include/.

Starting from include/yk/json20.hpp, every #include <yk/json20/...> is replaced
by the file's contents, once per file, in the order they are first reached;
standard headers are kept at their first occurrence only. The parts keep
their include guards, so the single header and the split headers can still be
included together.

This is a textual concatenation on purpose, not a preprocessor run: a
preprocessor would resolve #if (such as the unsigned __int128 check in
u128.hpp) for the machine doing the bundling, and inline its standard library.

usage: python3 tools/amalgamate.py [OUTPUT]
       (OUTPUT defaults to single_include/yk/json20.hpp, which git ignores)
"""

import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
INCLUDE = os.path.join(ROOT, 'include')
ENTRY = 'yk/json20.hpp'
DEFAULT_OUTPUT = os.path.join(ROOT, 'single_include', 'yk', 'json20.hpp')

PROJECT_INCLUDE = re.compile(r'#include <(yk/json20(?:/[^>]+)?\.hpp)>\s*$')
SYSTEM_INCLUDE = re.compile(r'#include <[^>]+>\s*$')

HEADER = """\
// json20: single-header form.
// Generated by tools/amalgamate.py from the headers under include/; do not
// edit. Distributed under the Boost Software License, Version 1.0.

"""


def amalgamate():
    seen_files = set()
    seen_system = set()
    out = []

    def inline(path):
        if path in seen_files:
            return
        seen_files.add(path)
        depth = 0
        with open(os.path.join(INCLUDE, path)) as f:
            for line in f:
                stripped = line.strip()
                if stripped.startswith('#if'):
                    depth += 1
                elif stripped.startswith('#endif'):
                    depth -= 1
                match = PROJECT_INCLUDE.match(stripped)
                if match:
                    # an include inside a conditional would need the condition kept
                    assert depth == 1, f'{path}: conditional #include'
                    inline(match.group(1))
                    continue
                if SYSTEM_INCLUDE.match(stripped):
                    assert depth == 1, f'{path}: conditional #include'
                    if stripped in seen_system:
                        continue
                    seen_system.add(stripped)
                out.append(line)
        out.append('\n')

    inline(ENTRY)
    text = HEADER + ''.join(out)
    # the removed includes leave runs of blank lines
    text = re.sub(r'\n{3,}', '\n\n', text)
    return text.rstrip('\n') + '\n'


def main():
    if len(sys.argv) > 2 or sys.argv[1:2] in (['-h'], ['--help']):
        print(__doc__, file=sys.stderr)
        return 2
    output = sys.argv[1] if len(sys.argv) == 2 else DEFAULT_OUTPUT
    text = amalgamate()
    os.makedirs(os.path.dirname(os.path.abspath(output)), exist_ok=True)
    with open(output, 'w') as f:
        f.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
