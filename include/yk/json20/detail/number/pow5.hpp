// Powers of five
//
// F(q) is 5^q scaled into [2^127, 2^128) and rounded down, q in [-342, 326].
// Every table the conversions need derives from it (see
// tools/gen_pow5_table.py): every 27th F is stored, and the rest is recovered
// as the top 128 bits of base * 5^offset plus a 2-bit correction.

struct pow5 {
  static constexpr int q_min = -342;
  static constexpr int q_max = 326;
  static constexpr int ratio = 27;
  static constexpr int grid0 = -351;

  // generated by tools/gen_pow5_table.py
  static constexpr u128 bases[] = {
      {0x8049a4ac0c5811ae, 0x205b896d777d6278},
      {0xcf42894a5dce35ea, 0x52064cac828675b9},
      {0xa76c582338ed2621, 0xaf2af2b80af6f24e},
      {0x873e4f75e2224e68, 0x5a7744a6e804a291},
      {0xda7f5bf590966848, 0xaf39a475506a899e},
      {0xb080392cc4349dec, 0xbd8d794d96aacfb3},
      {0x8e938662882af53e, 0x547eb47b7282ee9c},
      {0xe65829b3046b0afa, 0x0cb4a5a3112a5112},
      {0xba121a4650e4ddeb, 0x92f34d62616ce413},
      {0x964e858c91ba2655, 0x3a6a07f8d510f86f},
      {0xf2d56790ab41c2a2, 0xfae27299423fb9c3},
      {0xc428d05aa4751e4c, 0xaa97e14c3c26b886},
      {0x9e74d1b791e07e48, 0x775ea264cf55347d},
      {0x8000000000000000, 0x0000000000000000},
      {0xcecb8f27f4200f3a, 0x0000000000000000},
      {0xa70c3c40a64e6c51, 0x999090b65f67d924},
      {0x86f0ac99b4e8dafd, 0x69a028bb3ded71a3},
      {0xda01ee641a708de9, 0xe80e6f4820cc9495},
      {0xb01ae745b101e9e4, 0x5ec05dcff72e7f8f},
      {0x8e41ade9fbebc27d, 0x14588f13be847307},
      {0xe5d3ef282a242e81, 0x8f1668c8a86da5fa},
      {0xb9a74a0637ce2ee1, 0x6d953e2bd7173692},
      {0x95f83d0a1fb69cd9, 0x4abdaf101564f98e},
      {0xf24a01a73cf2dccf, 0xbc633b39673c8cec},
      {0xc3b8358109e84f07, 0x0a862f80ec4700c8},
      {0x9e19db92b4e31ba9, 0x6c07a2c26a8346d1},
  };
  static constexpr std::uint64_t corrections[] = {
      0x1501000455555551,
      0x0001400041450500,
      0x9565555944541005,
      0x4105540544544116,
      0x1041551596525555,
      0x4010404441054005,
      0x0000000010040015,
      0x9551556955400000,
      0x0010000050401165,
      0x4515544115051554,
      0x0000045451055195,
      0x0000000000000000,
      0x0000000000000000,
      0x969965a555590000,
      0x5050155555455505,
      0x0010555514545511,
      0x5515541000110100,
      0x4415050445545455,
      0x0010000000015414,
      0x0000000400400000,
      0x0100000000000000,
  };

  static constexpr std::array<std::uint64_t, ratio> small_pow5 = [] {
    std::array<std::uint64_t, ratio> p{};
    p[0] = 1;
    for (int i = 1; i < ratio; ++i) p[i] = p[i - 1] * 5;
    return p;
  }();

  static constexpr u128 floor(int q) noexcept
  {
    int const i = (q - grid0) / ratio;
    int const offset = (q - grid0) % ratio;
    std::uint64_t const correction = (corrections[(q - q_min) / 32] >> (2 * ((q - q_min) % 32))) & 3;
    u128 const base = bases[i];
    if (offset == 0) return add(base, correction);

    // 192-bit product base * 5^offset as top:mid:low, keeping its top 128
    // bits; top is nonzero because base >= 2^127 and 5^offset >= 5
    std::uint64_t const p = small_pow5[std::size_t(offset)];
    u128 const low = umul128(base.lo, p);
    u128 const high = umul128(base.hi, p);
    std::uint64_t const mid = high.lo + low.hi;
    std::uint64_t const top = high.hi + (mid < high.lo ? 1 : 0);
    int const shift = 64 - std::countl_zero(top);
    return add({(top << (64 - shift)) | (mid >> shift), (mid << (64 - shift)) | (low.lo >> shift)}, correction);
  }

  // F(q) is exact (5^q fits in 128 bits) only for these q
  static constexpr bool is_exact(int q) noexcept { return 0 <= q && q <= 55; }

  // fast_float's power_of_five_128[q]
  static constexpr u128 eisel_lemire(int q) noexcept { return add(floor(q), (-27 <= q && q < 0) ? 1 : 0); }

  // Dragonbox's caches: 10^k rounded up, 128 bits for binary64, 64 bits for binary32
  static constexpr u128 dragonbox_binary64(int k) noexcept { return add(floor(k), is_exact(k) ? 0 : 1); }
  static constexpr std::uint64_t dragonbox_binary32(int k) noexcept
  {
    u128 const f = floor(k);
    return f.hi + ((f.lo != 0 || !is_exact(k)) ? 1 : 0);
  }
};

