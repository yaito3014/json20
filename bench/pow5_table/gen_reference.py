"""Writes reference.inc: every F(q) as test data for both variants."""

from pow5_reference import Q_MIN, table

with open('reference.inc', 'w') as out:
    out.write(f'// generated by gen_reference.py: F(q) for q = {Q_MIN} ...\n')
    for v in table():
        out.write(f'{{0x{v >> 64:016x}, 0x{v & (2**64 - 1):016x}}},\n')
